"""Regenerate docs/PROGRESS.md from the build plan and the step records that exist in docs/steps/."""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLAN = ROOT / "docs/superpowers/specs/2026-11-05-three-way-match-rebuild-design.md"
STEPS = ROOT / "docs/steps"
OUT = ROOT / "docs/PROGRESS.md"

# Which system components each phase builds, for the system map.
COMPONENTS = [
    ("pdfs", "Source PDFs<br/>Hugging Face", 1), ("read", "Read<br/>fetch · render · parse<br/>clean · extract", 1),
    ("xcheck", "Cross-check<br/>PDF text layer", 1), ("match", "Rule matcher", 2),
    ("state", "State machine<br/>+ Postgres", 3), ("queue", "Job queue<br/>+ worker", 3),
    ("api", "API + webhooks", 4), ("ingest", "Ingestion<br/>replay · reconcile", 5),
    ("checks", "Duplicate · fraud<br/>injection checks", 6), ("agent", "Resolution agent", 7),
    ("approve", "Human approval", 8), ("exec", "Executor<br/>erp_postings", 8),
    ("obs", "Traces · logs · alerts", 9), ("cloud", "Cloud Run + Supabase", 11),
]
EDGES = ["ingest --> api", "api --> queue", "queue --> state", "pdfs --> read", "pdfs --> xcheck", "state --> read",
         "read --> checks", "checks --> match", "xcheck --> match", "match -- clean --> approve",
         "match -- exception --> agent", "agent --> approve", "approve --> exec"]


def plan():
    phases, current = [], None
    for line in PLAN.read_text().splitlines():
        if m := re.match(r"### Phase (\d+): (.+)", line):
            current = {"n": int(m[1]), "name": m[2], "steps": []}
            phases.append(current)
        elif current and (m := re.match(r"\| (\d+)\.(\d+) \| ([^|]+) \|", line)):
            step_id = f"{int(m[1]):02d}.{m[2]}"
            record = next(STEPS.glob(f"{step_id}-*.md"), None)
            current["steps"].append({"id": step_id, "what": m[3].strip(), "record": record})
    return phases


def main() -> None:
    phases = plan()
    all_steps = [s for p in phases for s in p["steps"]]
    done = sum(1 for s in all_steps if s["record"])
    next_step = next((s for s in all_steps if not s["record"]), None)
    built_phase = max((p["n"] for p in phases if p["steps"] and all(s["record"] for s in p["steps"])), default=-1)

    def phase_class(p):
        finished = sum(1 for s in p["steps"] if s["record"])
        if finished == len(p["steps"]):
            return "done"
        return "next" if next_step in p["steps"] else "todo"

    lines = [
        "# Build progress",
        "",
        f"**{done} of {len(all_steps)} steps done.** Next: **{next_step['id']} {next_step['what']}**." if next_step else f"**All {len(all_steps)} steps done.**",
        "",
        "Generated by `scripts/progress.py` from the [build plan](superpowers/specs/2026-11-05-three-way-match-rebuild-design.md) and the records in [steps/](steps/). Green is done, orange is in progress, dashed is not started.",
        "",
        "## Phases",
        "",
        "```mermaid",
        "flowchart TB",
    ]
    rows = [("Build the pieces", range(0, 4)), ("Connect them", range(4, 8)), ("Finish and ship", range(8, 12))]
    for title, numbers in rows:
        lines += [f'  subgraph row{numbers.start}["{title}"]', "    direction LR"]
        group = [p for p in phases if p["n"] in numbers]
        for p in group:
            finished = sum(1 for s in p["steps"] if s["record"])
            lines.append(f'    P{p["n"]}["{p["n"]} · {p["name"]}<br/>{finished}/{len(p["steps"])}"]:::{phase_class(p)}')
        lines += ["    " + " --> ".join(f"P{p['n']}" for p in group), "  end"]
    lines += ["  row0 --> row4 --> row8"]
    lines += _classes() + ["```", "", "## What exists in the system so far", "", "```mermaid", "flowchart LR"]
    platform_nodes = []
    platform = {"obs", "cloud"}
    for key, label, phase in COMPONENTS:
        state = "done" if phase <= built_phase else ("next" if next_step and int(next_step["id"][:2]) == phase else "todo")
        node = f'["{label}"]:::{state}'
        lines.append(f"  {key}{node}" if key not in platform else f"  %% {key} in platform")
        if key in platform:
            platform_nodes.append(f"    {key}{node}")
    lines += ['  subgraph platform["Around everything"]', "    direction TB", *platform_nodes, "  end"]
    lines += [f"  {edge}" for edge in EDGES] + _classes() + ["```", "", "## Steps", ""]
    for p in phases:
        lines += [f"### Phase {p['n']}: {p['name']}", "", "| Step | What | Status |", "|---|---|---|"]
        for s in p["steps"]:
            if s["record"]:
                status = f"done · [record](steps/{s['record'].name})"
            else:
                status = "**next**" if s is next_step else "not started"
            lines.append(f"| {s['id']} | {s['what']} | {status} |")
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"{done}/{len(all_steps)} steps done; next: {next_step['id'] if next_step else 'none'}; wrote {OUT.relative_to(ROOT)}")


def _classes():
    return [
        "  classDef done fill:#d8eeea,stroke:#2a9d8f,color:#1c2530",
        "  classDef next fill:#f8ead2,stroke:#d7932a,stroke-width:3px,color:#1c2530",
        "  classDef todo fill:#ffffff,stroke:#9aa5b1,stroke-dasharray:4 4,color:#586473",
    ]


if __name__ == "__main__":
    main()
